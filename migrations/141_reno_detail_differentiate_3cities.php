$cityName = ['kaohsiung'=>'高雄','tainan'=>'台南','taichung'=>'台中'];
$bkDir = __DIR__ . '/../_backups';
@mkdir($bkDir, 0755, true);
$bkFile = $bkDir . '/reno_detail_diff_' . date('Ymd-His') . '.json';
$backup = [];

try {
    $db->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
    $db->beginTransaction();
    foreach ($data as $citySlug => $d) {
        $old = $db->query("SELECT id,meta_desc,intro_html,faqs FROM geo_category_pages WHERE city_slug=" . $db->quote($citySlug) . " AND category_id=$catId AND service_slug='reno-detail'")->fetch(PDO::FETCH_ASSOC);
        if (!$old) { throw new Exception("找不到 $citySlug reno-detail 內容頁"); }
        $backup[$citySlug] = $old;

        $faqsJson = json_encode($d['faqs'], JSON_UNESCAPED_UNICODE);
        $st = $db->prepare("UPDATE geo_category_pages SET meta_desc=?, intro_html=?, faqs=?, updated_at=NOW() WHERE id=?");
        $st->execute([$d['meta_desc'], $d['intro_html'], $faqsJson, $old['id']]);
        echo "✅ {$cityName[$citySlug]} (id={$old['id']}) 已更新：intro " . mb_strlen(strip_tags($old['intro_html'])) . "→" . mb_strlen(strip_tags($d['intro_html'])) . " 字\n";
    }
    file_put_contents($bkFile, json_encode($backup, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));
    $db->commit();
    echo "\n備份舊值：_backups/" . basename($bkFile) . "\n完成。嘉義未動。\n";
} catch (Throwable $e) {
    if ($db->inTransaction()) $db->rollBack();
    fwrite(STDERR, "ERROR: " . $e->getMessage() . "\n");
    exit(1);
}
